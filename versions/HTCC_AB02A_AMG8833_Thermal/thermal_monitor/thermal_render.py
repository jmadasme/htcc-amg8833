_colormap_cache = {}


def get_colormap():
    """Devuelve el colormap turbo como array numpy (256,3) en 0-255."""
    if "turbo" not in _colormap_cache:
        stops = _TURBO_STOPS
        n = stops.shape[0]
        new_idx = np.linspace(0, n - 1, 256)
        old_idx = np.arange(n)
        out = np.empty((256, 3))
        for c in range(3):
            out[:, c] = np.interp(new_idx, old_idx, stops[:, c])
        _colormap_cache["turbo"] = (np.clip(out, 0, 1) * 255).astype(np.uint8)
    return _colormap_cache["turbo"]


def render_thermal_heatmap(pixels_C, size=720, vmin=None, vmax=None):
    """Convierte la matriz 8x8 en una imagen térmica suave (PIL RGB).

    Args:
        pixels_C: lista de 64 floats (orden fila-mayor) en °C.
        size:     lado de la imagen de salida en píxeles.
        vmin:     límite inferior de escala (°C). None = automático.
        vmax:     límite superior de escala (°C). None = automático.

    Returns:
        (PIL.Image RGB, vmin, vmax) con la imagen ya coloreada.
    """
    grid = np.array(pixels_C, dtype=float).reshape(8, 8)

    if vmin is None:
        vmin = float(grid.min())
    if vmax is None:
        vmax = float(grid.max())
    if vmax - vmin < 1e-6:
        vmax = vmin + 1e-6

    # Normalizar a 0..1
    norm = (grid - vmin) / (vmax - vmin)
    norm = np.clip(norm, 0.0, 1.0)

    # Ampliar 8x8 -> size usando interpolación bicúbica de Pillow
    # (partimos de una versión en gris de alta resolución para no perder
    #  precisión al colorizar).
    norm_img = Image.fromarray((norm * 255).astype(np.uint8), mode="L")
    norm_img = norm_img.resize((size, size), Image.BICUBIC)

    # Mapear a color usando el colormap
    lut = get_colormap()
    data = np.array(norm_img).astype(np.uint16)  # 0..255
    rgb = lut[data]  # (size, size, 3)
    img = Image.fromarray(rgb, mode="RGB")

    return img, vmin, vmax


def render_colorbar(height=420, width=36, vmin=0, vmax=1):
    """Genera una barra de color vertical para indicar la escala en °C.

    Returns:
        (PIL.Image RGB, vmin, vmax) donde cada píxel de arriba->abajo va
        de vmin (frío) a vmax (calor).
    """
    lut = get_colormap()
    # crear gradiente vertical (de abajo frío a arriba caliente)
    grad = np.linspace(0, 255, height).astype(np.uint8)  # 0 arriba? lo invertimos
    # queremos: arriba = vmax (calor), abajo = vmin (frío)
    # en colormap 255 = rojo/calor, 0 = azul/frío
    rows = []
    for y in range(height):
        # y=0 arriba -> vmax (255); y=height abajo -> vmin (0)
        v = 255 - int(y / max(height - 1, 1) * 255)
        color = lut[v]
        row = np.tile(color, (width, 1))
        rows.append(row)
    arr = np.stack(rows, axis=0)  # (height, width, 3)
    return Image.fromarray(arr, mode="RGB")
